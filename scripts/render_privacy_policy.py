"""Render the public and offline Android policies from PRIVACY.md.

Run with --check to detect stale copies without changing files.
"""

import argparse
import html
from pathlib import Path


def render(root: Path) -> dict[Path, str]:
    policy = (root / "PRIVACY.md").read_text()
    paragraphs = policy.strip().split("\n\n")
    body = []
    for paragraph in paragraphs:
        if paragraph.startswith("# "):
            body.append(f"<h1>{html.escape(paragraph[2:])}</h1>")
        elif paragraph.startswith("## "):
            body.append(f"<h2>{html.escape(paragraph[3:])}</h2>")
        else:
            body.append(f"<p>{html.escape(paragraph)}</p>")
    page = """<!doctype html>
<html lang="en">
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>HAMediaConnect Privacy Policy</title>
<style>
body { max-width: 48rem; margin: 3rem auto; padding: 0 1.25rem;
       font: 1rem/1.65 system-ui, sans-serif; color: #291c52; background: #f6f5fb; }
h1, h2 { line-height: 1.25; }
p { overflow-wrap: anywhere; }
</style>
<main>
""" + "\n".join(body) + "\n</main>\n</html>\n"
    plain = "\n\n".join(p.removeprefix("## ").removeprefix("# ") for p in paragraphs)
    # Android string resources interpret quotes and backslashes independently of XML.
    escaped = html.escape(plain, quote=False).replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    resource = ('<?xml version="1.0" encoding="utf-8"?>\n'
                '<!-- Generated by scripts/render_privacy_policy.py from PRIVACY.md. -->\n'
                '<resources>\n'
                '    <string name="privacy_policy_url" translatable="false">https://emarrero-personal.github.io/HAMediaConnect/</string>\n'
                f'    <string name="privacy_policy" translatable="false">{escaped}</string>\n'
                '</resources>\n')
    return {
        root / "docs/privacy-policy.html": page,
        root / "app/src/main/res/values/privacy_policy.xml": resource,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    for path, content in render(root).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale policy: {path.relative_to(root)}")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
